/* ==========================================================================
   ASTRALIS — THE DEVELOPMENT STYLE-PROP TABLE
   --------------------------------------------------------------------------
   The library has no spec at runtime, yet the development warning for an
   ignored style prop (utils/dev-identity.ts) must judge exactly as the
   validator does. So the spec emitter writes what that judgement needs into
   src/utils/dev-style-props.ts: every style-prop name by group, and for each
   component (by the name `identify` gives it) the groups it takes plus its own
   props and element attributes that share a style prop's name.

   The file is generated and drift-checked like the token CSS: the build fails
   when it no longer matches the spec, and `pnpm run gen:dev-props` rewrites
   it (then build again, so dist carries the new table).
   ========================================================================== */

/* Mirrors HTML_ATTRIBUTE_NAMES in astralis-cli's validate-core.mjs: names
   that are real HTML attributes on some element, so never reported. */
export const HTML_ATTRIBUTE_NAMES = ["width", "height", "size", "color", "wrap", "align", "border"];

const quote = (value) => JSON.stringify(value);

/* Mirrors LOOK_PROPS and lookHint in astralis-cli's validate-core.mjs. */
const LOOK_PROPS = ["variant", "size", "colorScheme"];
const lookOf = (entry) => LOOK_PROPS.filter((prop) => entry?.props?.[prop]);
const or = (list) => (list.length > 1 ? `${list.slice(0, -1).join(", ")} or ${list.at(-1)}` : (list[0] ?? ""));

/**
 * The source of src/utils/dev-style-props.ts for a spec.
 * @param {object} spec the system spec being emitted
 * @param {Record<string, unknown>} rootExports the built entry's exports
 * @returns {{ source: string, problems: string[] }}
 */
export function renderDevStyleProps(spec, rootExports) {
  const problems = [];
  const groupNames = Object.keys(spec.propGroups);
  const html = new Set(HTML_ATTRIBUTE_NAMES);
  const rows = new Map();
  const looks = new Map();
  for (const [name, entry] of Object.entries(spec.components)) {
    const identity = rootExports[name]?.displayName;
    if (typeof identity !== "string" || !entry.ownStyleProps) continue;
    const inGroups = new Set(entry.groups.flatMap((group) => Object.keys(spec.propGroups[group])));
    const extras = [...new Set([...entry.ownStyleProps, ...(entry.domStyleProps ?? [])])]
      .filter((prop) => !inGroups.has(prop) && !html.has(prop))
      .sort();
    const row = [entry.groups.join(" "), extras.join(" ")];
    const seen = rows.get(identity);
    if (seen && (seen[0] !== row[0] || seen[1] !== row[1])) {
      problems.push(`dev style-prop table: "${identity}" is two components that take different style props (${seen} | ${row})`);
    }
    rows.set(identity, row);
    if (row[0] === "placement") {
      const owner = entry.partOf;
      const ownerName = owner ? (rootExports[owner]?.displayName ?? owner) : "";
      looks.set(identity, [ownerName, or(lookOf(owner ? spec.components[owner] : entry))]);
    }
  }

  const lines = [
    "/* GENERATED by scripts/gen-system-spec.mjs (scripts/dev-style-props.mjs) from",
    "   the system spec. Do not edit: run `pnpm run gen:dev-props`, then build again.",
    "   Read only in development, by utils/dev-identity.ts. */",
    "",
    "/** Every style-prop name, by group, long spellings included. */",
    "export const STYLE_PROP_GROUPS: Record<string, readonly string[]> = {",
    ...groupNames.map((group) => `  ${group}: ${quote(Object.keys(spec.propGroups[group]))},`),
    "};",
    "",
    "/** HTML attributes that share a style prop's name; never reported. */",
    `export const HTML_ATTRIBUTE_NAMES: readonly string[] = ${quote(HTML_ATTRIBUTE_NAMES)};`,
    "",
    "/** Component name -> [the groups it takes, its other style-prop names], space-separated. */",
    "export const COMPONENT_STYLE_PROPS: Record<string, readonly [string, string]> = {",
    ...[...rows.keys()].sort().map((identity) => `  ${quote(identity)}: [${quote(rows.get(identity)[0])}, ${quote(rows.get(identity)[1])}],`),
    "};",
    "",
    "/** Component name -> [the compound it is a part of, or \"\"; the look props to reach for, as words], for the paint-prop hint. */",
    "export const LOOK_HINTS: Record<string, readonly [string, string]> = {",
    ...[...looks.keys()].sort().map((identity) => `  ${quote(identity)}: [${quote(looks.get(identity)[0])}, ${quote(looks.get(identity)[1])}],`),
    "};",
    "",
  ];
  return { source: lines.join("\n"), problems };
}
