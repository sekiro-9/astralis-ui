/**
 * Writes the command reference into the README and the docs site's CLI page
 * from the command table (src/lib/commands.mjs), so neither can drift from
 * `--help`. `node scripts/reference.mjs` rewrites both;
 * test/reference.test.mjs fails when either is stale.
 *
 * README: everything between the reference:start/end comments.
 * Docs page: the first `| Option |` table under each `## \`command\`` heading,
 * and under `## Global options` (MDX can't carry the README's HTML comments).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { COMMANDS, GLOBAL_OPTIONS } from "../src/lib/commands.mjs";

export const README = fileURLToPath(new URL("../README.md", import.meta.url));
export const DOCS_PAGE = fileURLToPath(new URL("../../astralis-docs/src/app/docs/cli/page.mdx", import.meta.url));

const START = "<!-- reference:start (generated by scripts/reference.mjs; edit src/lib/commands.mjs) -->";
const END = "<!-- reference:end -->";

const cell = (text) => text.replaceAll("|", "\\|");
const flag = (o) => `\`${o.short ? `-${o.short}, ` : ""}--${o.name}${o.type === "string" ? ` <${o.arg ?? "value"}>` : ""}\``;

export function optionsTable(options) {
  const rows = options.map((o) => {
    const extra = o.default ? ` Default: ${o.default}.` : "";
    return `| ${cell(flag(o))} | ${cell(o.description + extra)} |`;
  });
  return ["| Option | |", "| --- | --- |", ...rows].join("\n");
}

export function readmeReference() {
  const sections = COMMANDS.map((c) =>
    [
      `### \`astralis ${c.name}${c.args ? ` ${c.args}` : ""}\``,
      "",
      `${c.summary}.`,
      "",
      optionsTable(c.options),
      ...(c.notes ?? []).flatMap((note) => ["", note]),
      "",
      "```bash",
      ...c.examples,
      "```",
    ].join("\n"),
  );
  const globals = ["### Global options", "", "Every command takes these.", "", optionsTable(GLOBAL_OPTIONS)].join("\n");
  return [START, "", ...sections.flatMap((s) => [s, ""]), globals, "", END].join("\n");
}

export function syncReadme(text) {
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start === -1 || end === -1) throw new Error("README.md lost its reference:start/end markers");
  return text.slice(0, start) + readmeReference() + text.slice(end + END.length);
}

/** Replace the first options table in the section whose heading matches. */
function replaceTable(text, heading, table) {
  const at = text.search(heading);
  if (at === -1) throw new Error(`the CLI docs page has no section matching ${heading}`);
  const next = text.slice(at + 1).search(/^## /m);
  const sectionEnd = next === -1 ? text.length : at + 1 + next;
  const tableStart = text.indexOf("| Option |", at);
  if (tableStart === -1 || tableStart > sectionEnd) throw new Error(`no options table under ${heading}`);
  let tableEnd = tableStart;
  while (tableEnd < text.length && text[tableEnd] === "|") {
    const newline = text.indexOf("\n", tableEnd);
    tableEnd = newline === -1 ? text.length : newline + 1;
  }
  const trailing = text.slice(tableStart, tableEnd).endsWith("\n") ? "\n" : "";
  return text.slice(0, tableStart) + table + trailing + text.slice(tableEnd);
}

export function syncDocsPage(text) {
  let next = text;
  for (const c of COMMANDS) next = replaceTable(next, new RegExp(`^## \`${c.name}\``, "m"), optionsTable(c.options));
  return replaceTable(next, /^## Global options/m, optionsTable(GLOBAL_OPTIONS));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, sync] of [[README, syncReadme], [DOCS_PAGE, syncDocsPage]]) {
    const before = readFileSync(file, "utf8");
    const after = sync(before);
    if (after !== before) writeFileSync(file, after);
    console.log(`${after === before ? "up to date" : "updated"}  ${file}`);
  }
}
